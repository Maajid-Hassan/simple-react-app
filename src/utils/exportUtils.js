    doc.setFontSize(13);
    doc.setFont(undefined, 'bold');
    doc.setTextColor(40, 40, 40);
    doc.text('Task List', margin, yPosition);
    yPosition += 8;

    // Table headers
    doc.setFontSize(10);
    doc.setFont(undefined, 'bold');
    doc.setTextColor(79, 70, 229);
    doc.setFillColor(240, 240, 255);
    
