    yPosition += 6;

    const completed = filteredTasks.filter(t => t.completed).length;
    const pending = filteredTasks.length - completed;
    const completionRate = filteredTasks.length > 0 
      ? ((completed / filteredTasks.length) * 100).toFixed(1)
      : 0;

